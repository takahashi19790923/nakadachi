import { z } from "zod";
import { ja } from "zod/locales";

/**
 * 検証エラーの既定文言を日本語にする。
 *
 * ★これが無いと、利用者の画面に "Invalid input" と英語で出る。★
 * 実際に出た（2026-08-16、投稿フォームで種別を選ばずに送信したとき）。
 * 個々の項目に文言を書き忘れても、英語が漏れないようにする。
 *
 * 優先順位は
 *   ①各スキーマに書いた文言 → ②ここの customError → ③zod の日本語ロケール
 * の順で、上が勝つ。実測で確認済み。
 *
 * ★zod のロケールをそのまま使うだけでは足りない。★ 既定は
 * 「無効な入力: stringが期待されましたが、undefinedが入力されました」
 * のような開発者向けの文言で、そのまま出すものではない。
 * よくある2つ（未入力・選択肢の不一致）だけこちらで置き換え、
 * 残りはロケールに任せる。
 *
 * ★このモジュールは副作用のために import する。★ 消すと英語に戻る。
 * 検証スキーマを書くファイルの先頭で必ず読み込むこと。
 */
z.config({
  localeError: ja().localeError,
  customError: (issue) => {
    /*
     * ★選択肢の判定を先に置く。★ 未選択のラジオ・セレクトは
     * invalid_value で来る（値が undefined でも入力エラーではない）。
     * 順番を逆にすると、選ぶ項目に「入力してください」と出て指示が食い違う。
     */
    if (issue.code === "invalid_value") return "選択してください";
    // 値そのものが来ていない。必須の入力欄の未記入がここに来る。
    if (issue.input === undefined) return "入力してください";
    return undefined;
  },
});
